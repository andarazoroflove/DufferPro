lines.append('    }')
lines.append('    if (min_y < 0) min_y = 0;')
lines.append('    if (max_y >= SPLASH_H) max_y = SPLASH_H - 1;')
lines.append('')
lines.append('    int nodes[64];')
lines.append('    for (int y = min_y; y <= max_y; ++y) {')
lines.append('        int node_count = 0;')
lines.append('        int j = n - 1;')
lines.append('        for (int i = 0; i < n; ++i) {')
lines.append('            int yi = pts[i].y, yj = pts[j].y;')
lines.append('            if ((yi < y && yj >= y) || (yj < y && yi >= y)) {')
lines.append('                if (node_count < 64) {')
lines.append('                    int xi = pts[i].x, xj = pts[j].x;')
lines.append('                    int x = xi + (int)(((int64_t)(y - yi) * (xj - xi)) / (yj - yi));')
lines.append('                    nodes[node_count++] = x;')
lines.append('                }')
lines.append('            }')
lines.append('            j = i;')
lines.append('        }')
lines.append('        for (int a = 0; a < node_count - 1; ++a) {')
lines.append('            for (int b = a + 1; b < node_count; ++b) {')
lines.append('                if (nodes[a] > nodes[b]) {')
lines.append('                    int tmp = nodes[a]; nodes[a] = nodes[b]; nodes[b] = tmp;')
lines.append('                }')
lines.append('            }')
lines.append('        }')
lines.append('        for (int k = 0; k < node_count - 1; k += 2) {')
lines.append('            int x1 = nodes[k];')
lines.append('            int x2 = nodes[k + 1];')
lines.append('            if (x1 < 0) x1 = 0;')
lines.append('            if (x2 >= SPLASH_W) x2 = SPLASH_W - 1;')
lines.append('            if (x2 >= x1) {')
