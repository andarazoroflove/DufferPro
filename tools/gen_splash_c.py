lines.append('    int rx2 = rx * rx;')
lines.append('    int ry2 = ry * ry;')
lines.append('    if (rx2 == 0 || ry2 == 0) return;')
lines.append('    int a = (color >> 24) & 0xFF;')
lines.append('')
lines.append('    for (int y = min_y; y <= max_y; ++y) {')
lines.append('        int dy = y - cy;')
lines.append('        int dy2 = dy * dy;')
lines.append('        if (dy2 > ry2) continue;')
lines.append('        int span = (int)sqrt((double)(rx2 * (ry2 - dy2)) / (double)ry2);')
lines.append('        int x1 = cx - span; if (x1 < 0) x1 = 0;')
lines.append('        int x2 = cx + span; if (x2 >= SPLASH_W) x2 = SPLASH_W - 1;')
lines.append('        uint32_t *row = &dst[y * SPLASH_W];')
lines.append('        for (int x = x1; x <= x2; ++x) {')
lines.append('            if (a == 255) {')
lines.append('                row[x] = color;')
lines.append('            } else if (a > 0) {')
lines.append('                uint32_t bg = row[x];')
lines.append('                int bg_r = (bg >> 16) & 0xFF, bg_g = (bg >> 8) & 0xFF, bg_b = bg & 0xFF;')
lines.append('                int fg_r = (color >> 16) & 0xFF, fg_g = (color >> 8) & 0xFF, fg_b = color & 0xFF;')
lines.append('                int r = bg_r + (((fg_r - bg_r) * a) >> 8);')
lines.append('                int g = bg_g + (((fg_g - bg_g) * a) >> 8);')
lines.append('                int b = bg_b + (((fg_b - bg_b) * a) >> 8);')
lines.append('                row[x] = COLOR_RGB(r, g, b);')
lines.append('            }')
lines.append('        }')
lines.append('    }')
lines.append('}')
